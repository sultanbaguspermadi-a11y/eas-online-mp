// Mirrors the browser's pure game modules into the Edge Function bundle, so the server runs the SAME rules, scoring and validator
// as the local game (no hand-copied subset). The Supabase CLI only bundles files inside supabase/functions/, hence the mirror.
//   node tools/sync-edge-shared.mjs          write the mirror
//   node tools/sync-edge-shared.mjs --check  exit 1 if the mirror is out of date (used by the test-suite and CI)
import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'supabase/functions/_shared/game');
const FILES = ['config.js', 'modes.js', 'rules.js', 'wordpolicy.js', 'validator.js',
  'dictionary/clitics.js', 'dictionary/dawg.js', 'dictionary/lexicon.js', 'dictionary/mined.js', 'dictionary/morphology.js', 'dictionary/normalize.js'];
const banner = f => `// GENERATED by tools/sync-edge-shared.mjs from js/${f}. Do not edit here: change js/${f} and re-run the tool.\n`;
let stale = 0;
for (const f of FILES) {
  const want = banner(f) + fs.readFileSync(path.join(root, 'js', f), 'utf8');
  const dest = path.join(out, f);
  const have = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : null;
  if (have === want) continue;
  stale++;
  if (process.argv.includes('--check')) { console.error('out of date: supabase/functions/_shared/game/' + f); continue; }
  fs.mkdirSync(path.dirname(dest), { recursive: true }); fs.writeFileSync(dest, want);
}
if (process.argv.includes('--check')) { if (stale) { console.error('Run: node tools/sync-edge-shared.mjs'); process.exit(1); } console.log('edge shared modules are in sync'); }
else console.log(stale ? `synced ${stale} file(s)` : 'already in sync');
