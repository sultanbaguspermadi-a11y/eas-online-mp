// Vercel build step: writes js/online/env.js from environment variables. Only PUBLIC values are accepted.
//   SUPABASE_URL        https://<project-ref>.supabase.co
//   SUPABASE_ANON_KEY   the public anon / publishable key (safe in browsers)
import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url';
const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'js/online/env.js');
const url = (process.env.SUPABASE_URL || '').trim(), key = (process.env.SUPABASE_ANON_KEY || '').trim();
if (/service_role/i.test(key) || (key.split('.')[1] && /service_role/.test(Buffer.from(key.split('.')[1], 'base64url').toString('utf8')))) {
  console.error('Refusing to build: SUPABASE_ANON_KEY looks like a service-role key. Use the public anon/publishable key.'); process.exit(1);
}
if (!url || !key) console.warn('SUPABASE_URL / SUPABASE_ANON_KEY not set: the site will build with online play disabled (local play still works).');
fs.writeFileSync(out, `// GENERATED by tools/write-env.mjs at build time. Public values only.\nexport const ONLINE_ENV = ${JSON.stringify({ url, anonKey: key })};\n`);
console.log('wrote js/online/env.js (' + (url ? 'configured' : 'empty') + ')');
